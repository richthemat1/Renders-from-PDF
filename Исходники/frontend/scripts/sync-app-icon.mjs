import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../../assets/app-icon.ico", import.meta.url));
const destination = fileURLToPath(new URL("../public/app-icon.ico", import.meta.url));
const available = existsSync(source);
mkdirSync(fileURLToPath(new URL("../public/", import.meta.url)), { recursive: true });
if (available) copyFileSync(source, destination);
else rmSync(destination, { force: true });
writeFileSync(new URL("../src/app-icon.generated.ts", import.meta.url),
  `// Generated by scripts/sync-app-icon.mjs; edit assets/app-icon.ico instead.\nexport const APP_ICON_AVAILABLE = ${available};\n`);
console.log(available ? "App icon: assets/app-icon.ico" : "App icon: built-in fallback");
